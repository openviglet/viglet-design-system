#!/usr/bin/env node
/**
 * VDS241 — the phone-first reference: four artboards at 390 × 844, drawn from
 * the tokens.
 *
 *   node scripts/phone-reference.mjs           # write docs/reference/phone-*.dc.html
 *   node scripts/phone-reference.mjs --check   # fail when a committed board is stale
 *
 * The other artboards start at a desktop width and shrink. A phone-first app has
 * a different skeleton: a tab bar is the navigation, the primary action sits in
 * a thumb's reach, a confirmation is a sheet from the bottom, and every target
 * is the touch height. These draw that skeleton, with role labels only, and
 * every colour on them is a token resolved for its ground by
 * `scripts/lib/contrast.mjs`, the way `site.dc.html` is drawn. The rules they
 * draw are BENTO-AUTHORING §8.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import { groundTokens, hex, over, parseColour } from "./lib/contrast.mjs"
import { tokensJson } from "./lib/tokens-json.mjs"

export const WIDTH = 390
export const HEIGHT = 844

/** iOS's insets at this size: the status bar above, the home indicator below. */
const TOP = 47
const BOTTOM = 34
const TAB_BAR = 49

/** The record states, in the order a reader meets them. */
const STATES = ["published", "draft", "scheduled", "changed", "archived"]
const STATE_WORDS = { published: "Published", draft: "Draft", scheduled: "Scheduled", changed: "Changed", archived: "Archived" }

const escape = (text) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")

/** One ground's colours, opaque, as the hex a browser paints. */
export function palette(preset, ground) {
  const { tokens } = groundTokens([{ name: "preset.css", css: preset }], ground, "cool")
  const page = parseColour(tokens.get("--vg-background"), tokens)
  const paint = (name) => {
    const colour = parseColour(tokens.get(name) ?? "", tokens)
    if (!colour) throw new Error(`phone-reference: ${name} does not resolve on ${ground}`)
    return hex(colour.alpha < 1 ? over(colour, page) : colour)
  }
  const names = [
    "background", "foreground", "muted-foreground", "card", "muted", "border", "primary", "primary-foreground",
    "destructive", "accent-fill-from", "accent-fill-to", "accent-surface", "accent-fg",
    ...STATES.map((s) => `bento-state-${s}`),
  ]
  return Object.fromEntries(names.map((name) => [name, paint(`--vg-${name}`)]))
}

/** The sizes the boards draw at, from tokens.json, so a changed scale redraws them. */
export function sizes(preset) {
  const { dimension } = tokensJson(preset)
  const px = (name) => dimension[name].$extensions["com.viglet"].reactNative
  return { touch: px("control-touch"), control: px("radius-control"), panel: px("radius-panel") }
}

const statusBar = (c) => `
    <div style="height:${TOP}px;display:flex;align-items:flex-end;justify-content:space-between;padding:0 28px 8px;font-size:15px;font-weight:600;color:${c.foreground}">
      <span>9:41</span><span style="display:flex;gap:5px;align-items:center"><span style="width:17px;height:10px;border-radius:2px;background:${c.foreground}"></span><span style="width:24px;height:11px;border-radius:3px;border:1.5px solid ${c.foreground}"></span></span>
    </div>`

const homeIndicator = (c) =>
  `<div style="height:${BOTTOM}px;display:flex;align-items:flex-end;justify-content:center;padding-bottom:8px"><span style="width:134px;height:5px;border-radius:3px;background:${c.foreground}"></span></div>`

const glyph = (colour, size = 22) =>
  `<span aria-hidden="true" style="width:${size}px;height:${size}px;border-radius:6px;border:2px solid ${colour};display:inline-block;box-sizing:border-box"></span>`

const note = (text, c) => `<span class="mono" style="font-size:9.5px;color:${c["accent-fg"]}">${escape(text)}</span>`

const stateMarker = (state, c) =>
  `<span class="state" data-state="${state}" data-colour="${c[`bento-state-${state}`]}" style="display:inline-flex;align-items:center;gap:6px;font-size:12px;color:${c["muted-foreground"]}"><span style="width:6px;height:6px;border-radius:50%;background:${c[`bento-state-${state}`]}"></span>${STATE_WORDS[state]}</span>`

function frame(title, ground, c, body) {
  return `<!doctype html>
<html>
<head>
  <meta charset="utf-8">
  <script src="./support.js"></script>
</head>
<body>
<!-- Generated by scripts/phone-reference.mjs from src/styles/preset.css (VDS241). Do not edit: run the script. -->
<x-dc>
<helmet>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap">
  <style>
    body { margin: 0; background: #ffffff; }
    x-dc { display: block; }
    helmet { display: none; }
    .vg { font-family: "Inter", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; -webkit-font-smoothing: antialiased; }
    .mono { font-family: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace; }
  </style>
</helmet>

<div class="vg" data-ground="${ground}" title="${escape(title)}" style="position:relative;width:${WIDTH}px;height:${HEIGHT}px;background:${c.background};color:${c.foreground};overflow:hidden;display:flex;flex-direction:column">${body}
</div>
</x-dc>
</body>
</html>
`
}

/** A tab bar of four destinations, one active, and the one primary action above it. */
function tabs(c, s) {
  const items = [1, 2, 3, 4]
    .map((n) => {
      const active = n === 1
      const colour = active ? c.primary : c["muted-foreground"]
      return `<span class="tab" ${active ? 'aria-current="page" ' : ""}style="flex:1;display:flex;flex-direction:column;align-items:center;justify-content:center;gap:3px;min-height:${s.touch}px;color:${colour};font-size:10.5px;font-weight:${active ? 600 : 500}">${glyph(colour)}Area ${n}</span>`
    })
    .join("")
  const cards = [1, 2, 3]
    .map(
      (n) => `
        <div style="border:1px solid ${c.border};border-radius:${s.panel}px;background:${c.card};padding:14px 16px">
          <div style="font-size:15px;font-weight:600">Entity name ${n}</div>
          <div style="font-size:13px;color:${c["muted-foreground"]};margin-top:2px">Meta, one line</div>
        </div>`,
    )
    .join("")
  return `${statusBar(c)}
    <div style="padding:6px 20px 12px"><div style="font-size:12px;color:${c["muted-foreground"]};letter-spacing:0.06em">EYEBROW</div><div style="font-size:30px;font-weight:700;letter-spacing:-0.02em">Area 1</div></div>
    <div style="flex:1;display:flex;flex-direction:column;gap:10px;padding:0 16px">${cards}
      <div style="margin-top:4px">${note("the page scrolls; the tab bar and the action stay", c)}</div>
    </div>
    <div class="primary-action" data-px="${s.touch}" style="position:absolute;right:16px;bottom:${TAB_BAR + BOTTOM + 16}px;height:${s.touch}px;padding:0 20px;border-radius:999px;display:flex;align-items:center;gap:8px;color:#ffffff;font-size:15px;font-weight:600;background:linear-gradient(120deg,${c["accent-fill-from"]},${c["accent-fill-to"]});box-shadow:0 6px 16px rgba(0,0,0,0.18)">+ Primary action</div>
    <div class="tab-bar" data-px="${TAB_BAR}" style="border-top:1px solid ${c.border};background:${c.card};display:flex;height:${TAB_BAR}px">${items}</div>
    <div style="background:${c.card}">${homeIndicator(c)}</div>`
}

/** A confirmation as a sheet: the page dimmed, the decision at the bottom, both buttons at the touch height. */
function sheet(c, s) {
  return `${statusBar(c)}
    <div style="padding:6px 20px"><div style="font-size:30px;font-weight:700;letter-spacing:-0.02em">Entity name</div></div>
    <div style="flex:1;padding:0 16px"><div style="height:220px;border:1px solid ${c.border};border-radius:${s.panel}px;background:${c.card}"></div></div>
    <div style="position:absolute;inset:0;background:rgba(0,0,0,0.4)"></div>
    <div class="sheet" style="position:absolute;left:0;right:0;bottom:0;background:${c.card};border-radius:${s.panel * 2}px ${s.panel * 2}px 0 0;padding:8px 20px 0">
      <div style="display:flex;justify-content:center;padding-bottom:14px"><span style="width:36px;height:5px;border-radius:3px;background:${c.border}"></span></div>
      <div style="font-size:18px;font-weight:600">Delete Entity name?</div>
      <div style="font-size:14px;color:${c["muted-foreground"]};margin:6px 0 20px;line-height:1.45">This will permanently delete Entity name. This action cannot be undone.</div>
      <div class="control" data-px="${s.touch}" style="height:${s.touch}px;border-radius:${s.control}px;background:${c.destructive};color:#ffffff;display:flex;align-items:center;justify-content:center;font-size:15px;font-weight:600">Delete</div>
      <div class="control" data-px="${s.touch}" style="height:${s.touch}px;border-radius:${s.control}px;border:1px solid ${c.border};display:flex;align-items:center;justify-content:center;font-size:15px;font-weight:600;margin-top:10px">Cancel</div>
      <div style="margin-top:8px">${note("the consequence in the body; the action names the verb", c)}</div>
      ${homeIndicator(c)}
    </div>`
}

/** A list of records: a search at the touch height, rows that carry the state as a dot and a word. */
function list(c, s) {
  const rows = STATES.map(
    (state, i) => `
        <div class="row" style="display:flex;align-items:center;gap:12px;min-height:64px;padding:0 16px;border-bottom:1px solid ${c.border}">
          <span style="flex:1;min-width:0;display:flex;flex-direction:column;gap:3px"><span style="font-size:15px;font-weight:500">Entity name ${i + 1}</span>${stateMarker(state, c)}</span>
          <span style="font-size:12px;color:${c["muted-foreground"]}">${i + 2} days ago</span>
          <span aria-hidden="true" style="color:${c["muted-foreground"]};font-size:18px">›</span>
        </div>`,
  ).join("")
  return `${statusBar(c)}
    <div style="padding:6px 20px 10px"><div style="font-size:30px;font-weight:700;letter-spacing:-0.02em">Entities</div></div>
    <div style="padding:0 16px 10px"><div class="control" data-px="${s.touch}" style="height:${s.touch}px;border-radius:${s.control}px;background:${c.muted};display:flex;align-items:center;padding:0 14px;font-size:15px;color:${c["muted-foreground"]}">Search…</div></div>
    <div style="flex:1;background:${c.card};border-top:1px solid ${c.border}">${rows}
      <div style="padding:12px 16px">${note("a row is 64 px: two lines, one target", c)}</div>
    </div>
    <div style="background:${c.card}">${homeIndicator(c)}</div>`
}

/** A full-screen surface on the dark ground: the frame owns the screen, the controls sit on its edges. */
function fullscreen(c, s) {
  const round = (size, label) =>
    `<span class="control" data-px="${size}" aria-label="${label}" style="width:${size}px;height:${size}px;border-radius:50%;border:1.5px solid ${c.border};background:${c.muted};display:inline-flex;align-items:center;justify-content:center">${glyph(c.foreground, 18)}</span>`
  return `${statusBar(c)}
    <div style="display:flex;justify-content:space-between;padding:4px 16px">${round(s.touch, "Close")}${round(s.touch, "Option")}</div>
    <div style="flex:1;display:flex;align-items:center;justify-content:center;padding:24px">
      <div style="width:100%;aspect-ratio:3 / 4;border:2px dashed ${c["muted-foreground"]};border-radius:${s.panel * 2}px;display:flex;align-items:center;justify-content:center;color:${c["muted-foreground"]};font-size:13px">The frame</div>
    </div>
    <div style="display:flex;align-items:center;justify-content:space-around;padding:8px 24px 16px">
      ${round(s.touch, "Secondary")}
      <span class="control" data-px="72" aria-label="Primary" style="width:72px;height:72px;border-radius:50%;border:4px solid ${c.foreground};display:inline-flex;align-items:center;justify-content:center"><span style="width:56px;height:56px;border-radius:50%;background:${c.foreground}"></span></span>
      ${round(s.touch, "Secondary")}
    </div>
    <div style="text-align:center">${note("dark ground whatever the app's mode; nothing under the controls", c)}</div>
    ${homeIndicator(c)}`
}

/** The four boards, by file name. */
export const BOARDS = [
  { file: "phone-tabs.dc.html", title: "A tab bar and the primary action", ground: "light", draw: tabs },
  { file: "phone-list.dc.html", title: "Records in rows, each with its state", ground: "light", draw: list },
  { file: "phone-sheet.dc.html", title: "A confirmation as a bottom sheet", ground: "light", draw: sheet },
  { file: "phone-fullscreen.dc.html", title: "A full-screen surface, dark ground", ground: "dark", draw: fullscreen },
]

/** Every board, for the preset's current tokens, as `{ file: html }`. */
export function phoneReference(preset) {
  const s = sizes(preset)
  const grounds = { light: palette(preset, "light"), dark: palette(preset, "dark") }
  return Object.fromEntries(BOARDS.map((b) => [b.file, frame(b.title, b.ground, grounds[b.ground], b.draw(grounds[b.ground], s))]))
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
export const DIR = join(root, "docs", "reference")

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const boards = phoneReference(readFileSync(join(root, "src", "styles", "preset.css"), "utf8"))
  if (process.argv.includes("--check")) {
    const stale = Object.entries(boards).filter(([file, html]) => readFileSync(join(DIR, file), "utf8") !== html)
    if (stale.length > 0) {
      console.error(`phone-reference: ${stale.map(([f]) => f).join(", ")} stale; run node scripts/phone-reference.mjs`)
      process.exit(1)
    }
    console.log("phone-reference: the phone boards match the tokens")
  } else {
    for (const [file, html] of Object.entries(boards)) writeFileSync(join(DIR, file), html)
    console.log(`phone-reference: wrote ${Object.keys(boards).length} boards to docs/reference`)
  }
}
